package br.com.timasters.app.data.routers.firmware

import br.com.timasters.app.core.network.SubnetUtils

/** Pure rules for custom OpenWrt images: compatibility, package lists and first-boot script. */
object FirmwareRules {

    /** The script the image builder accepts is limited to 40 KB. */
    const val MAX_DEFAULTS_LENGTH = 40_960

    /**
     * The profile whose supported_devices contains the router's own board name
     * (`ubus call system board` → board_name, e.g. "tplink,archer-c6-v2"). This is the same check
     * sysupgrade does, so an image from another hardware revision can never be offered.
     */
    fun profileForBoard(profiles: TargetProfiles, boardName: String): Pair<String, DeviceProfile>? {
        val board = boardName.trim().lowercase()
        if (board.isEmpty()) return null
        return profiles.profiles.entries.firstOrNull { (_, profile) -> profile.supportedDevices.any { it.lowercase() == board } }?.toPair()
            ?: profiles.profiles.entries.firstOrNull { it.key == board.replace(',', '_') }?.toPair()
    }

    /** Devices whose names contain every word of [query] ("archer c6", "tp-link c6 v2"). */
    fun search(overview: List<OverviewProfile>, query: String, limit: Int = 50): List<OverviewProfile> {
        val words = query.lowercase().split(Regex("[\\s]+")).filter { it.isNotBlank() }
        if (words.isEmpty()) return emptyList()
        return overview.filter { profile ->
            val text = (profile.names + profile.id).joinToString(" ").lowercase()
            words.all { it in text }
        }.take(limit)
    }

    /** Presets on top of what the user already installed, without duplicates and honoring "-pkg" removals. */
    fun packages(installed: List<String>, presets: Collection<PackagePreset>): List<String> {
        val requested = presets.flatMap { it.packages }
        val removed = requested.filter { it.startsWith("-") }.map { it.removePrefix("-") }.toSet()
        return (installed.filter { it !in removed } + requested).distinct()
    }

    /**
     * Built images: sysupgrade for routers already on OpenWrt, factory for the first install from
     * stock. No fallback: a sysupgrade image sent through a vendor page can brick the device, and
     * devices without a factory image need a model-specific procedure (see the OpenWrt wiki).
     */
    fun pickImage(images: List<FirmwareImage>, firstInstall: Boolean): FirmwareImage? =
        images.firstOrNull { it.type == if (firstInstall) "factory" else "sysupgrade" }

    /** /tmp is in RAM: keep a safety margin so the router doesn't run out of memory while flashing. */
    fun fitsInMemory(imageSize: Int, availableMemory: Long?): Boolean =
        availableMemory == null || availableMemory > imageSize * 3L / 2

    fun isValidHostname(name: String) = name.isEmpty() || Regex("^[A-Za-z0-9-]{1,63}$").matches(name)

    /** Problems with the first-boot settings, as messages keys for the UI. */
    fun validate(settings: FirstBootSettings): List<SettingsProblem> = buildList {
        if (!isValidHostname(settings.hostname)) add(SettingsProblem.HOSTNAME)
        if (settings.lanIp.isNotEmpty() && !SubnetUtils.isValidIpv4(settings.lanIp)) add(SettingsProblem.LAN_IP)
        if (settings.wifiName.length > 32) add(SettingsProblem.WIFI_NAME)
        if (settings.wifiPassword.isNotEmpty() && settings.wifiPassword.length !in 8..63) add(SettingsProblem.WIFI_PASSWORD)
        if (settings.wifiPassword.isNotEmpty() && settings.wifiName.isEmpty()) add(SettingsProblem.WIFI_NAME)
    }

    /**
     * uci-defaults script run once on the first boot, based on the OpenWrt firmware selector's own
     * template. Always sets Brazil's time zone and Wi-Fi country; the rest only when filled in.
     */
    fun defaultsScript(settings: FirstBootSettings): String = buildString {
        appendLine("#!/bin/sh")
        appendLine("# Generated by TI Masters")
        if (settings.hostname.isNotEmpty()) appendLine("uci set system.@system[0].hostname=${quote(settings.hostname)}")
        appendLine("uci set system.@system[0].zonename='America/Sao Paulo'")
        appendLine("uci set system.@system[0].timezone='<-03>3'")
        appendLine("uci commit system")
        if (settings.lanIp.isNotEmpty()) {
            appendLine("uci set network.lan.ipaddr=${quote(settings.lanIp)}")
            appendLine("uci commit network")
        }
        appendLine("i=0")
        appendLine("while uci -q get wireless.@wifi-device[\$i] >/dev/null; do")
        appendLine("  uci set wireless.@wifi-device[\$i].country='BR'")
        if (settings.wifiName.isNotEmpty()) appendLine("  uci set wireless.@wifi-device[\$i].disabled='0'")
        appendLine("  i=\$((i+1))")
        appendLine("done")
        if (settings.wifiName.isNotEmpty()) {
            appendLine("i=0")
            appendLine("while uci -q get wireless.@wifi-iface[\$i] >/dev/null; do")
            appendLine("  uci set wireless.@wifi-iface[\$i].disabled='0'")
            appendLine("  uci set wireless.@wifi-iface[\$i].ssid=${quote(settings.wifiName)}")
            if (settings.wifiPassword.isNotEmpty()) {
                appendLine("  uci set wireless.@wifi-iface[\$i].encryption='psk2'")
                appendLine("  uci set wireless.@wifi-iface[\$i].key=${quote(settings.wifiPassword)}")
            }
            appendLine("  i=\$((i+1))")
            appendLine("done")
        }
        appendLine("uci commit wireless")
        appendLine("exit 0")
    }

    /** Single-quoted shell string; a ' inside becomes '\'' so values can't break out of the quotes. */
    fun quote(value: String): String = "'" + value.replace("'", "'\\''") + "'"
}

enum class SettingsProblem { HOSTNAME, LAN_IP, WIFI_NAME, WIFI_PASSWORD }
